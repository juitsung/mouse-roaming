#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn windows_vk_round_trip() {
        let keys = [
            KeyCode::A,
            KeyCode::Z,
            KeyCode::Key0,
            KeyCode::F12,
            KeyCode::LeftCtrl,
            KeyCode::RightCtrl,
            KeyCode::LeftMeta,
            KeyCode::Enter,
            KeyCode::NumpadEnter,
            KeyCode::ArrowUp,
            KeyCode::Space,
        ];
        for key in keys {
            let (vk, ext) = key.to_windows_vk().expect("vk exists");
            let back = KeyCode::from_windows_vk(vk, ext).expect("from_vk");
            assert_eq!(key, back);
        }
    }

    #[test]
    fn macos_keycode_round_trip() {
        let keys = [
            KeyCode::A,
            KeyCode::C,
            KeyCode::V,
            KeyCode::Key9,
            KeyCode::F1,
            KeyCode::LeftMeta,
            KeyCode::RightMeta,
            KeyCode::LeftCtrl,
            KeyCode::LeftAlt,
            KeyCode::ArrowLeft,
            KeyCode::Enter,
            KeyCode::Backspace,
        ];
        for key in keys {
            let code = key.to_macos_keycode().expect("macos code exists");
            let back = KeyCode::from_macos_keycode(code).expect("from_macos");
            assert_eq!(key, back);
        }
    }
}
